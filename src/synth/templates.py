PLACES = ("Павлодар", "Караганда", "Костанай", "Аксу", "Экибастуз",
          "Талгар", "Конаев", "Сарань", "Рудный", "Балхаш")
PLACES_KK = ("Павлодар", "Қарағанды", "Қостанай", "Ақсу", "Екібастұз",
             "Талғар", "Қонаев", "Саран", "Рудный", "Балқаш")
DURATIONS = ("со вчерашнего дня", "уже неделю", "третий день", "больше месяца")
DURATIONS_KK = ("кешеден бері", "бір аптадан бері", "үшінші күн", "бір айдан астам")
RU_FRAMES = (
    "Из города {place} поступило сообщение: {issue}. Просьба проверить ситуацию.",
    "Город {place}, {duration}: {issue}. Когда это исправят?",
    "Повторное обращение из города {place}: {issue}. Нужен ответ по срокам.",
    "Город {place}. {Issue}. Пожалуйста, направьте ответ через службу 109.",
)
KK_FRAMES = (
    "{place} тұрғыны хабарлайды: {issue}. Жағдайды тексеруді сұрайды.",
    "{place} қаласында {duration} мына мәселе бар: {issue}. Қашан шешіледі?",
    "{place} қаласынан қайта өтініш түсті: {issue}. Мерзімі туралы жауап керек.",
    "{place} қаласы. {Issue}. 109 қызметі арқылы жауап беруді сұрайды.",
)


def build() -> list[dict]:
    assert set(ISSUES) == set(TOPICS)
    rng = np.random.default_rng(SEED)
    rows: list[dict] = []
    seen: set[str] = set()
    for ci, topic in enumerate(TOPICS):
        for lang, frames, places, durations, idx in (
            ("ru", RU_FRAMES, PLACES, DURATIONS, 0),
            ("kk", KK_FRAMES, PLACES_KK, DURATIONS_KK, 1),
        ):
            # Каждая из 3 ситуаций используется не меньше 13 раз, каждая из
            # 4 рамок — 10. Случайный выбор только переставляет сочетания.
            pairs = [(i % 3, i % 4) for i in range(PER_LANGUAGE)]
            rng.shuffle(pairs)
            for n, (issue_i, frame_i) in enumerate(pairs):
                issue = ISSUES[topic][issue_i][idx]
                for _ in range(100):
                    text = frames[frame_i].format(
                        place=str(rng.choice(places)),
                        duration=str(rng.choice(durations)),
                        issue=issue[0].lower() + issue[1:],
                        Issue=issue,
                    )
                    key = norm(text)
                    if key not in seen:
                        break
                else:
                    raise ValueError(f"не удалось собрать уникальный текст: C-{ci:02d}-{lang}-{n:02d}")
                seen.add(key)
                hits = pii_hits(text)
                if hits:
                    raise ValueError(f"ПДн в C-{ci:02d}-{lang}-{n:02d}: {hits}")
                rows.append({"id": f"C-{ci:02d}-{lang}-{n:02d}",
                             "text": text, "label": topic, "lang": lang,
                             "generator": "template", "author": "Codex"})
    assert len(rows) == len(TOPICS) * PER_LANGUAGE * 2
    return rows


def main() -> None:
    rows = build()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
    print(f"шаблонных текстов C: {len(rows)}; классов: {len(TOPICS)}; "
          f"на язык и класс: {PER_LANGUAGE}")


if __name__ == "__main__":
    main()
