def normalize(v):
    return "" if v is None else str(v).strip().lower().replace("ё", "е")

def map_topic(value):
    v = normalize(value)
    if not v:
        return "прочее"
    for topic, keys in RULES:
        for k in keys:
            if k.replace("ё", "е") in v:
                return topic
    return "прочее"

def main():
    src = Path("data/unified.parquet")
    if not src.exists():
        sys.exit("нет data/unified.parquet — сначала src/adapters/build_unified.py")
    df = pd.read_parquet(src, columns=["region", "category"])

    # Караганда: 638 строк со сдвигом полей портят sub_category.
    # Их темы в маппинг не пускаем — берём словарь тем из чистой части.
    import csv
    csv.field_size_limit(10**9)
    GOOD = {"Быстрый ответ", "Письменное обращение", ""}
    kar = Path("drive-download-20260907T161509Z-1-001/"
               "Обращения граждан 109 - Карагандинская область.csv")
    bad_themes = set()
    if kar.exists():
        rows = list(csv.DictReader(open(kar, encoding="utf-8-sig", newline="")))
        broken = [r for r in rows if (r["answer_type"] or "") not in GOOD]
        clean = {r["sub_category"] for r in rows if (r["answer_type"] or "") in GOOD}
        bad_themes = {r["sub_category"] for r in broken} - clean
        print(f"Караганда: {len(broken)} строк со сдвигом полей, "
              f"{len(bad_themes)} тем встречаются только в них — исключены из маппинга\n")

    df["topic"] = df["category"].map(map_topic)
    mask_bad = (df["region"] == "Карагандинская область") & df["category"].isin(bad_themes)
    df = df[~mask_bad]

    print(f"{'регион':32s} {'строк':>8s} {'тем':>5s} {'отобр.тем':>10s} "
          f"{'в прочее строк':>15s} {'доля':>8s}")
    fails = []
    for r, g in df.groupby("region", sort=False):
        themes = g["category"].dropna().unique()
        mapped = sum(1 for t in themes if map_topic(t) != "прочее")
        other = int((g["topic"] == "прочее").sum())
        share = other / len(g)
        flag = "" if share < 0.15 else "  <-- выше 15%"
        print(f"{r:32s} {len(g):8d} {len(themes):5d} {mapped:10d} "
              f"{other:15d} {100*share:7.1f}%{flag}")
        if share >= 0.15:
            fails.append(r)

    print("\nРаспределение по 12 темам (вся таблица):")
    vc = df["topic"].value_counts()
    for t in TOPICS:
        n = int(vc.get(t, 0))
        print(f"  {t:32s} {n:8d}  {100*n/len(df):5.2f}%")

    for r, g in df.groupby("region", sort=False):
        oth = g[g["topic"] == "прочее"]
        if not len(oth):
            continue
        print(f"\n--- {r}: топ-30 тем, ушедших в «прочее» "
              f"({len(oth)} строк, {100*len(oth)/len(g):.1f}%)")
        for v, k in Counter(oth["category"].fillna("(пусто)")).most_common(30):
            print(f"  {k:7d}  {str(v)[:70]}")

    if fails:
        print(f"\nВЫШЕ ЦЕЛЕВЫХ 15%: {', '.join(fails)}")

if __name__ == "__main__":
    main()
