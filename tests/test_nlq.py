#!/usr/bin/env python3
"""Прогон src/nlq.py по 20 вопросам руководителя.

    .venv/bin/python -m tests.test_nlq

Вопросы взяты из `tests/nlq_questions.md` — списка, зафиксированного в git ДО
написания кода. Править список под то, что заработало, запрещено: если вопрос
не отвечается, правильный результат — отказ с причиной, а не удаление вопроса.

Три последних вопроса (21–23) в метрику не входят: это проверка того, что
система отказывает, а не выдумывает число.

ПЕРЕФРАЗЫ. Каждый вопрос задаётся ещё раз другими словами. Если разбор работает
только на дословной формулировке — это таблица подстановок, а не разбор вопроса,
и доля перефраз показывает, какое из двух построено.

Выход: reports/nlq.md (числа, запросы, оговорки) и reports/nlq_charts.html (графики).
"""
import sys
from pathlib import Path

import plotly.io as pio

from src.nlq import answer, load, num, render

OUT_MD = Path("reports/nlq.md")
OUT_HTML = Path("reports/nlq_charts.html")

# Дословно из tests/nlq_questions.md
QUESTIONS = [
    "Сколько обращений поступило за последний полный месяц?",
    "Больше или меньше, чем за тот же месяц год назад?",
    "Какие пять тем дают больше всего обращений за последний год?",
    "По какой теме обращений выросло сильнее всего за последний квартал против предыдущего?",
    "Какой регион дал больше всего обращений в прошлом месяце?",
    "Какая доля обращений — справочные, а не проблемы?",
    "Сколько обращений по теплоснабжению пришло в прошлый отопительный сезон?",
    "В какие дни недели нагрузка выше?",
    "Какая доля обращений закрыта?",
    "Сколько обращений просрочено и какая это доля?",
    "В каком районе больше всего жалоб на дороги?",
    "Как менялось число обращений по водоснабжению по месяцам за последний год?",
    "Какие темы растут быстрее всего год к году?",
    "Сколько обращений приходит в выходные?",
    "Какой исполнитель получает больше всего обращений?",
    "Когда был самый загруженный день за всю историю и по какой теме?",
    "Сколько обращений в среднем в день и как это менялось по годам?",
    "Какая доля всех обращений приходится на три крупнейшие темы?",
    "Сколько обращений по экологии за последние 12 месяцев в разрезе регионов?",
    "По каким темам обращения прекратились — были и перестали приходить?",
]

# Те же двадцать смыслов, сказанные иначе
PARAPHRASES = [
    "сколько всего было обращений в прошлом месяце",
    "в прошлом месяце обращений стало больше или меньше по сравнению с прошлым годом",
    "на что жалуются чаще всего за последний год",
    "какая тема сильнее всего выросла за квартал",
    "в какой области больше всего обратились в прошлом месяце",
    "какая часть звонков это просто справки",
    "сколько жалоб на отопление было за отопительный сезон",
    "в какой день недели звонят больше",
    "какой процент обращений уже закрыт",
    "какая доля обращений с нарушением срока",
    "где больше всего жалуются на ямы на дорогах",
    "покажи динамику обращений по воде по месяцам за год",
    "какие темы прибавили сильнее всего год к году",
    "много ли обращений в субботу и воскресенье",
    "на кого приходится больше всего обращений из исполнителей",
    "когда был пик обращений за всю историю",
    "сколько обращений в среднем в день по годам",
    "какая доля приходится на три самые крупные темы",
    "сколько обращений по экологии за последние 12 месяцев по регионам",
    "какие темы перестали приходить",
]

# ВТОРОЙ набор формулировок, написанный ПОСЛЕ правки разбора и ни разу не прогонявшийся
# до этого. Первый набор (PARAPHRASES) использовался, чтобы найти дыры в словаре, и
# поэтому его результат завышен: разбор чинился под него. Честная цифра — эта.
HELDOUT = [
    "сколько обращений зарегистрировали в прошедшем месяце",
    "в прошлом месяце поток вырос или упал относительно того же месяца годом ранее",
    "назови пять самых частых тем обращений за год",
    "какая тема дала наибольший прирост за последний квартал",
    "у какого региона наибольшее число обращений за прошлый месяц",
    "какой процент обращений это справочные звонки",
    "сколько было обращений по теплоснабжению за отопительный сезон",
    "по каким дням недели обращений больше всего",
    "какова доля закрытых обращений",
    "какой процент обращений просрочен",
    "в каком районе чаще всего жалуются на дороги",
    "как по месяцам менялось число обращений по канализации за последний год",
    "какие темы выросли сильнее всего по сравнению с прошлым годом",
    "какая доля обращений приходит в выходные дни",
    "у какого исполнителя больше всего обращений",
    "в какой день было больше всего обращений за всю историю",
    "среднее число обращений в день по каждому году",
    "какую долю занимают пять крупнейших тем",
    "сколько обращений по экологии за 12 месяцев в разрезе областей",
    "есть ли темы по которым обращения больше не поступают",
]

# Должны получить отказ с причиной
MUST_REFUSE = [
    "Сколько в среднем длится обработка обращения?",
    "На что жалуются чаще всего своими словами?",
    "Сколько обращений от одного и того же заявителя?",
]


def main():
    df, vocab = load()
    md = ["# Вопросы к данным: прогон по 20 вопросам руководителя\n",
          f"Источник — `data/unified.parquet`, {num(len(df))} строк. "
          + f"Опорная дата — последняя дата в данных, {vocab.ref:%Y-%m-%d}.\n",
          "Список вопросов зафиксирован в `tests/nlq_questions.md` до написания кода "
          "и под результат не правился.\n"]
    figs, ok, refused_wrongly = [], 0, []

    md.append("## Двадцать вопросов\n")
    for i, q in enumerate(QUESTIONS, 1):
        res = answer(q, df, vocab)
        md.append(render({**res, "question": f"{i}. {q}"}))
        if res.get("refused"):
            refused_wrongly.append((i, q, res["refused"]))
        else:
            ok += 1
            figs.append((f"{i}. {q}", res["figure"]))

    md.append("## Вопросы, на которые канон ответить не может\n")
    md.append("Правильный результат здесь — отказ с причиной. Число, выданное на такой "
              "вопрос, было бы хуже молчания.\n")
    refuse_ok = 0
    for q in MUST_REFUSE:
        res = answer(q, df, vocab)
        md.append(render(res))
        refuse_ok += bool(res.get("refused"))

    md.append("## Перефразы: разбор или таблица подстановок\n")
    md.append("Те же двадцать смыслов, сказанные другими словами. Совпадение намерения "
              "с исходным вопросом проверяется по типу запроса и разрезу.\n")
    md.append("| № | Перефраза | Намерение | Совпало с исходным |")
    md.append("|---|---|---|---|")
    same = 0
    for i, (orig, para) in enumerate(zip(QUESTIONS, PARAPHRASES), 1):
        a, b = answer(orig, df, vocab), answer(para, df, vocab)
        ka = None if a.get("refused") else (a["query"].metric, a["query"].group_by)
        kb = None if b.get("refused") else (b["query"].metric, b["query"].group_by)
        hit = ka is not None and ka == kb
        same += hit
        md.append(f"| {i} | {para} | {kb[0] if kb else 'отказ'}"
                  f"{' · ' + str(kb[1]) if kb and kb[1] else ''} | "
                  f"{'да' if hit else '**нет** — ' + (str(ka) + ' против ' + str(kb))} |")

    md.append("\n## Отложенный набор формулировок\n")
    md.append("Первый набор перефраз использовался, чтобы найти дыры в словаре разбора, "
              "и разбор под него чинился — значит, его результат завышен. Этот набор "
              "написан после правок и прогоняется впервые; его цифра и есть честная.\n")
    md.append("| № | Формулировка | Намерение | Совпало |")
    md.append("|---|---|---|---|")
    held = 0
    for i, (orig, para) in enumerate(zip(QUESTIONS, HELDOUT), 1):
        a, b = answer(orig, df, vocab), answer(para, df, vocab)
        ka = None if a.get("refused") else (a["query"].metric, a["query"].group_by)
        kb = None if b.get("refused") else (b["query"].metric, b["query"].group_by)
        hit = ka is not None and ka == kb
        held += hit
        md.append(f"| {i} | {para} | {kb[0] if kb else 'отказ'}"
                  f"{' · ' + str(kb[1]) if kb and kb[1] else ''} | "
                  f"{'да' if hit else '**нет** — ожидалось ' + str(ka)} |")

    md.insert(3, f"\n**Итог: разобрано {ok} из {len(QUESTIONS)}; отказов с причиной там, "
                 f"где ответить нельзя — {refuse_ok} из {len(MUST_REFUSE)}; "
                 f"перефраза даёт тот же разбор в {same} случаях из {len(PARAPHRASES)} "
                 f"(набор, под который чинился разбор) и в {held} из {len(HELDOUT)} "
                 f"на отложенном наборе.**\n")

    OUT_MD.parent.mkdir(exist_ok=True)
    OUT_MD.write_text("\n".join(md) + "\n", encoding="utf-8")
    parts = ["<meta charset='utf-8'><h1>Вопросы к данным — графики</h1>"]
    for j, (title, fig) in enumerate(figs):
        parts.append(f"<h3>{title}</h3>")
        # div_id задаётся явно: иначе plotly генерирует случайный, и файл меняется
        # при каждом прогоне, шумя в git при неизменных данных.
        parts.append(pio.to_html(fig, include_plotlyjs="cdn" if j == 0 else False,
                                 full_html=False, div_id=f"nlq-{j:02d}"))
    OUT_HTML.write_text("\n".join(parts), encoding="utf-8")

    print(f"разобрано {ok}/{len(QUESTIONS)} · отказов где надо {refuse_ok}/{len(MUST_REFUSE)}"
          f" · перефразы {same}/{len(PARAPHRASES)} · отложенный набор {held}/{len(HELDOUT)}")
    for i, q, why in refused_wrongly:
        print(f"  НЕ РАЗОБРАН {i}: {q}\n      {why[:120]}")
    print(f"отчёт: {OUT_MD} · графики: {OUT_HTML}")
    return 0 if (ok == len(QUESTIONS) and refuse_ok == len(MUST_REFUSE)) else 1


if __name__ == "__main__":
    sys.exit(main())
